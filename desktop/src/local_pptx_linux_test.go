func TestLocalPPTXPublishesHeldStageAfterDirectoryEntryChanges(t *testing.T) {
	root, err := os.OpenRoot(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()
	const target = "汇报.pptx"
	const report = "original generated bytes"
	var replacedPath string
	err = writeLocalPPTXOutput(docxSession{}, root, target, []byte(report), func() error {
		files, err := os.ReadDir(root.Name())
		if err != nil || len(files) != 1 {
			t.Fatalf("expected one staging entry, got %v, %v", files, err)
		}
		info, err := files[0].Info()
		if err != nil || !info.IsDir() || info.Mode().Perm() != 0700 {
			t.Fatalf("stage is not a private directory: %v, %v", info, err)
		}
		replacedPath = filepath.Join(root.Name(), files[0].Name())
		if err := os.Rename(replacedPath, filepath.Join(root.Name(), "moved-stage")); err != nil {
			t.Fatal(err)
		}
		return os.WriteFile(replacedPath, []byte("substituted bytes"), 0600)
	})
	if err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(filepath.Join(root.Name(), target))
	if err != nil || string(data) != report {
		t.Fatalf("published the wrong stage: %q, %v", data, err)
	}
	data, err = os.ReadFile(replacedPath)
	if err != nil || string(data) != "substituted bytes" {
		t.Fatalf("changed a replacement entry: %q, %v", data, err)
	}
}

func TestLocalPPTXCanRetryAfterPartialWrite(t *testing.T) {
	usePPTXTestRuntime(t)
	source, err := makeDOCX("验收 12 项")
	if err != nil {
		t.Fatal(err)
	}
	worker, session, request, output := newPPTXTestTask(t, source)
	var originalLimit unix.Rlimit
	if err = unix.Getrlimit(unix.RLIMIT_FSIZE, &originalLimit); err != nil {
		t.Fatal(err)
	}
	signal.Ignore(unix.SIGXFSZ)
	defer signal.Reset(unix.SIGXFSZ)
	limit := originalLimit
	limit.Cur = 4096
	limitOutput := true
	mockPPTXTestServer(t, func(r *http.Request, body map[string]string) (int, string) {
		if strings.HasSuffix(r.URL.Path, "/generate") {
			return http.StatusOK, pptxTestReport
		}
		if limitOutput && body["action"] == "create" {
			if err := unix.Setrlimit(unix.RLIMIT_FSIZE, &limit); err != nil {
				t.Fatal(err)
			}
		}
		return http.StatusOK, `{"allowed":true}`
	})
	task, err := worker.run(session, request, func() error { return nil })
	if restoreErr := unix.Setrlimit(unix.RLIMIT_FSIZE, &originalLimit); restoreErr != nil {
		t.Fatal(restoreErr)
	}
	if err == nil || task.Status != "failed" {
		t.Fatalf("task=%+v err=%v", task, err)
	}
	if _, err = os.Stat(output); !os.IsNotExist(err) {
		t.Fatalf("partial output remains: %v", err)
	}
	limitOutput = false
	task, err = worker.run(session, request, func() error { return nil })
	if err != nil || task.Status != "completed" {
		t.Fatalf("retry task=%+v err=%v", task, err)
	}
	deck, err := zip.OpenReader(output)
	if err != nil {
		t.Fatal(err)
	}
	deck.Close()
}
